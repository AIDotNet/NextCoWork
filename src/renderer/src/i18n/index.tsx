setPresenterTranslate((key, params) => translate(key, params));

export function localeLabel(locale: Locale): string {
  return messagesFor(locale)[
    locale === "zh-CN" ? "locale.name.zhCN" : "locale.name.enUS"
  ] as string;
}

/**
 * 运行期注册入口 —— 从这里再导一次,让消费者统一从 `../i18n` 进,
 * 不必记得插件文案住在哪个文件。实现与理由见 `plugin-messages.ts`。
 */
export {
  PluginMessageError,
  clearPluginMessages,
  pluginMessages,
  pluginMessagesVersion,
  registerPluginMessages,
  subscribePluginMessages,
  unregisterPluginMessages,
} from './plugin-messages';

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
}
const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({
  children,
  initialLocale = "zh-CN",
}: {
  children: ReactNode;
  initialLocale?: Locale;
}): ReactNode {
  const [locale, setLocale] = useState<Locale>(initialLocale);
  /*
    ★ 镜像在**渲染期**同步,不是在 effect 里。effect 晚一帧,而 `makeTab`
    可能在同一次事件里就被调用(切完语言立刻新建 Tab)—— 那一个 Tab 会拿到
    上一种语言的标题,而且它会跟着落盘,以后每次启动都是错的。
  */
  activeLocaleValue = locale;
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  /*
    ★ 订阅插件文案注册表。没有这一步,装完插件要重启才看得见它的文案 ——
    而「重启一下试试」正是插件系统最不该给人的第一印象。
    版本号进 `t` 的依赖数组,`t` 换了引用,所有消费者才会重渲。
  */
  const messagesVersion = useSyncExternalStore(
    subscribePluginMessages,
    pluginMessagesVersion,
    pluginMessagesVersion,
  );
  const t = useCallback<Translate>(
    (key, params = {}) =>
      // 兜底走 zh 的合并视图而不是裸 `ZH`:插件只提供了一种语言时,
      // 另一种语言下才不会掉回显示 key 本身。
      interpolate(messagesFor(locale)[key], messagesFor("zh-CN")[key], params, key),
    // messagesVersion 不在函数体里出现,它在这儿是**缓存失效信号**:
    // 插件装了新文案 → 版本变 → `t` 换引用 → 消费者重渲。
    [locale, messagesVersion],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (value === null)
    throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

/*
 * ★ 这个模块**不做局部热更,一改就整页重载**。
 *
 * `I18nContext` 是模块级 `createContext()` 的产物 —— 模块被重新执行一次,就多出
 * 一个全新的 Context 对象。而本文件导出的不只是组件(还有 `messagesFor`、
 * `SUPPORTED_LOCALES` 等),react-refresh 因此不会把它当成刷新边界,热更新会向
 * 上游 importer 传播,传播路径上谁先接住谁就地重渲 —— 结果是**已挂载的
 * `I18nProvider` 还提供着旧 Context,而更新之后才第一次加载的 lazy chunk
 * (views/registry.tsx 里那几个:DocumentView / ChatView / TerminalView …)
 * import 到的是新 Context**。新 Context 从来没有 Provider,`useContext` 取到
 * null,于是:
 *
 *     Uncaught Error: useI18n must be used inside I18nProvider
 *         at useI18n (index.tsx)
 *         at DocumentView (DocumentView.tsx)
 *
 * 报错点在 DocumentView,但它一行都没改 —— 改的是这里的文案。只要那个视图在
 * 你改文案之前恰好还没被打开过,就必然踩中;改完文案再开一个新 Tab 就是最典型
 * 的复现路径。手动刷新窗口即可恢复,但下一次改文案还会再来一遍。
 *
 * 所以这里显式自接管热更并整页重载。代价只是改文案时丢一次组件状态,
 * 换来「改文案绝不会把运行中的应用打成一个假崩溃」。
 */
if (import.meta.hot) {
  import.meta.hot.accept(() => {
    window.location.reload();
  });
}
