/**
 * IPC 路由边界分类表 —— controller-local / device / composed。
 *
 * ★ 这是**路由边界清单**,不是网络授权白名单。`device` 只说明这条频道在
 *   架构里属于哪一侧,**不代表它可以被网络调用**。任何网络侧进来的调用仍然
 *   必须:显式注册 schema、单独声明权限、并挂上 handler —— 三者缺一,
 *   这条频道在网络侧就是关着的。这张表不作为「这些频道可以远程调」的依据。
 *
 * - `controller-local`:只在控制端本地生效的频道(窗口控制、剪贴板、
 *   更新器、打开外部链接、把渲染层实体绑到本机 webContents)。
 * - `device`:设备侧的主进程能力(库读写、会话与 Agent 运行、终端、git、
 *   MCP……)。**生成时所有频道先落这一档**,再按下面那些指定例外覆写。
 * - `composed`:需要控制端与设备端**两侧协作**才能走完的频道(系统对话框
 *   取路径、凭据与 OAuth、导出导入、跨进程 tab 托管……)。
 *
 * ★ 为什么放 `shared/ipc/` 而不是 `shared/device/`:后者会随协议 SDK 一起被
 *   消费方加载,而这张表只需要 `contract.ts` 的**类型**(纯 type import,
 *   编译期擦除)。放这边不会把整套 IPC 类型拖进 SDK 的运行时。
 *
 * ★ 每个频道**单独写一个属性**,并用 `satisfies Record<频道联合, IpcBoundary>`
 *   做双向校验:契约里新增 / 删除一条频道而这里没跟上,typecheck 当场报错。
 *   **刻意不提供**任何按前缀推断或默认 fallback 的运行时放行 —— 分类只能
 *   一条条显式写出来,没有「没写就默认 device」的兜底。
 */
